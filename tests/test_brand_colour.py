"""The founder's accent colour: chosen in Settings, readable everywhere it is used.

The viewer's pages use
three shades of it, generated by the server: the button fill (--brand), text
and links (--brand-text), and the label on a button (--on-brand). Every pairing
the viewer uses must pass 4.5:1 in both themes, so a colour that would fail is
adjusted, and Settings says so.
"""

import time
from typing import Any

import pytest
from django.test import Client

from snug.accounts import sessions
from snug.accounts.models import Admin
from snug.audit.models import AuditEvent
from snug.core import brand
from snug.core.models import SiteSettings
from snug.documents.models import Document
from snug.links import service

pytestmark = pytest.mark.django_db

# Viewer surfaces, light and dark (DESIGN.md section 3.4).
LIGHT = ("#fafaf9", "#ffffff")
DARK = ("#1c1917", "#262220")


@pytest.mark.parametrize(
    ("raw", "expected"),
    [("#1F5F8B", "#1f5f8b"), ("1f5f8b", "#1f5f8b"), ("#abc", "#aabbcc"), (" #00aa55 ", "#00aa55")],
)
def test_colours_are_read_leniently(raw: str, expected: str) -> None:
    assert brand.parse(raw) == expected


@pytest.mark.parametrize("raw", ["red", "#12345", "#gggggg", "javascript:x", "", "#1f5f8b;}"])
def test_anything_else_is_refused(raw: str) -> None:
    assert brand.parse(raw) is None


@pytest.mark.parametrize(
    "accent",
    ["#1f5f8b", "#ffd400", "#808080", "#ff6200", "#000000", "#ffffff", "#00ff00", "#7a1fa2"],
)
def test_every_shade_is_readable_in_both_themes(accent: str) -> None:
    shades = brand.palette(accent)
    for background in LIGHT:
        assert brand.contrast(shades.text_light, background) >= 4.5
    for background in DARK:
        assert brand.contrast(shades.text_dark, background) >= 4.5
    assert brand.contrast(shades.on_light, shades.fill_light) >= 4.5
    assert brand.contrast(shades.on_dark, shades.fill_dark) >= 4.5


def test_a_dark_navy_is_used_as_it_is_in_light_mode() -> None:
    shades = brand.palette("#1f5f8b")
    assert shades.fill_light == "#1f5f8b"
    assert shades.text_light == "#1f5f8b"
    assert shades.on_light == "#ffffff"


def test_a_bright_yellow_is_deepened_for_text_and_labelled_dark() -> None:
    shades = brand.palette("#ffd400")
    assert shades.fill_light == "#ffd400"  # a bright button is fine with dark text on it
    assert shades.on_light == "#1c1917"
    assert shades.text_light != "#ffd400"
    assert shades.adjusted


# ---------------------------------------------------------------- Settings


@pytest.fixture
def client() -> Client:
    admin = Admin.objects.create(email="ruth@fernlea.example", is_active=True)
    browser = Client()
    browser.force_login(admin)
    session = browser.session
    session[sessions.LOGIN_AT] = session[sessions.LAST_ACTIVITY] = time.time()
    session.save()
    return browser


def save(client: Client, accent: str) -> Any:
    return client.post("/admin/settings/branding", {"accent": accent}, secure=True)


def test_settings_offers_it(client: Client) -> None:
    page = client.get("/admin/settings/", secure=True).content.decode()
    section = page[page.index('id="branding"') :]
    assert 'action="/admin/settings/branding#branding"' in section
    assert 'name="accent"' in section and 'type="color"' in section


def test_saving_a_colour(client: Client) -> None:
    response = save(client, "#1F5F8B")
    assert response.status_code == 302
    assert response["Location"] == "/admin/settings/?saved=branding#branding"
    assert SiteSettings.load().accent_colour == "#1f5f8b"
    event = AuditEvent.objects.get(action="settings.branding_changed")
    assert event.details == {"accent": "#1f5f8b"}
    page = client.get(response["Location"].split("#")[0], secure=True).content.decode()
    assert "Saved. Investors' pages use this colour." in page


def test_an_adjusted_colour_says_so(client: Client) -> None:
    response = save(client, "#ffd400")
    page = client.get(response["Location"].split("#")[0], secure=True).content.decode()
    assert "Text and links are darkened where needed to stay readable." in page


def test_a_bad_colour_is_refused(client: Client) -> None:
    response = save(client, "red")
    assert response.status_code == 400
    assert "Enter a colour like #1f5f8b." in response.content.decode()
    assert SiteSettings.load().accent_colour == ""


def test_the_default_can_be_restored(client: Client) -> None:
    save(client, "#ffd400")
    save(client, "")
    assert SiteSettings.load().accent_colour == ""


# ---------------------------------------------------------------- the viewer


def test_the_stylesheet_carries_the_shades(client: Client) -> None:
    save(client, "#ffd400")
    response = Client().get("/brand/brand.css", secure=True)
    assert response.status_code == 200
    assert response["Content-Type"] == "text/css; charset=utf-8"
    css = response.content.decode()
    shades = brand.palette("#ffd400")
    assert f"--brand: light-dark({shades.fill_light}, {shades.fill_dark});" in css
    assert f"--brand-text: light-dark({shades.text_light}, {shades.text_dark});" in css
    assert f"--on-brand: light-dark({shades.on_light}, {shades.on_dark});" in css


def test_without_a_colour_there_is_no_stylesheet() -> None:
    assert Client().get("/brand/brand.css", secure=True).status_code == 404


def test_viewer_pages_link_it_only_when_set(client: Client) -> None:
    deck = Document.objects.create(title="Seed deck")
    issued = service.create(
        document=deck,
        email="priya@northfield.example",
        note="",
        expires_at=None,
        require_verification=True,
        allow_download=True,
        created_by=None,
    )
    viewer = Client()
    assert "/brand/brand.css" not in viewer.get(f"/v/{issued.token}", secure=True).content.decode()
    save(client, "#ffd400")
    page = viewer.get(f"/v/{issued.token}", secure=True).content.decode()
    assert f'<link rel="stylesheet" href="/brand/brand.css?v={brand.version("#ffd400")}">' in page
